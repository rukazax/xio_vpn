#!/bin/sh
# xio-vpn4-setup.sh - install/refresh the vpn4 IPv4-over-NAT64 bridge.
#
# Works on an IPv6-only host that has a working NAT64 prefix but no IPv4 route.
# AmneziaWG clients keep their IPv6 tunnel; the server additionally gives them an
# IPv4 address out of 10.90.0.0/24, redirects their TCP and DNS to a userspace
# process, and that process re-emits the traffic as IPv6 towards
# <prefix>/96 + the original IPv4 destination, where the provider's NAT64 picks
# it up.  Nothing is routed or translated in the kernel.
#
#   ./xio-vpn4-setup.sh [PREFIX] [AWG_IF] [CLIENT_V4] [TUN_V4]
#
#   PREFIX      NAT64 prefix, /96 (default 2a01:4f8:c2c:123f:64:5)
#   AWG_IF      the existing AmneziaWG interface (default awg0)
#   CLIENT_V4   the client's IPv4 address inside the tunnel (default 10.90.0.2)
#   TUN_V4      the server's IPv4 address inside the tunnel (default 10.90.0.1)
#
# The binary is taken from $VPN4_BIN, else ./vpn4, else built from ./src/vpn4
# with the local Go toolchain.  The script is idempotent: it rewrites a file only
# when the content differs, restarts vpn4 only when the binary or its config
# changed, and re-applies the same rules with the xio-vpn4 comment tag.
set -eu

PREFIX=${1:-${VPN4_PREFIX:-2a01:4f8:c2c:123f:64:5}}
AWG_IF=${2:-${VPN4_AWG_IF:-awg0}}
CLIENT_V4=${3:-${VPN4_CLIENT_V4:-10.90.0.2}}
TUN_V4=${4:-${VPN4_TUN_V4:-10.90.0.1}}
TUN_CIDR=${VPN4_TUN_CIDR:-24}
TCP_PORT=${VPN4_TCP_PORT:-19192}
DNS_PORT=${VPN4_DNS_PORT:-5353}
DNS_UPSTREAM=${VPN4_DNS_UPSTREAM:-1.1.1.1:53}
TAG=xio-vpn4
CONF=/etc/xio-vpn4.conf
BIN=/usr/local/bin/vpn4
RULES=/usr/local/sbin/vpn4-rules.sh
AWG_DIR=/etc/awg-owner
AWG=/usr/local/bin/awg

HERE=$(cd "$(dirname "$0")" && pwd)

say() { echo "xio-vpn4-setup: $*"; }
die() { echo "xio-vpn4-setup: ERROR: $*" >&2; exit 1; }

[ "$(id -u)" = 0 ] || die "run as root"

# ------------------------------------------------------------------ 0. checks
python3 - "$PREFIX" <<'PY' || die "NAT64 prefix rejected: $PREFIX"
import ipaddress, sys
raw = sys.argv[1]
plen = '96'
if '/' in raw:
    raw, plen = raw.rsplit('/', 1)
if '::' not in raw:            # six groups are the natural spelling of a /96
    raw += '::'
net = ipaddress.IPv6Network('%s/%s' % (raw, plen), strict=False)
if net.prefixlen != 96:
    sys.exit('prefix length must be /96, got /%d' % net.prefixlen)
print('  prefix: %s' % net)
PY
[ -f "$HERE/vpn4-rules.sh" ] || die "vpn4-rules.sh is missing next to this script"

# ------------------------------------------------------- 1. the userspace binary
changed_bin=0
if [ -n "${VPN4_BIN:-}" ]; then
    src=$VPN4_BIN
elif [ -f "$HERE/vpn4" ]; then
    src=$HERE/vpn4
elif command -v go >/dev/null 2>&1 && [ -d "$HERE/src/vpn4" ]; then
    say "building vpn4 from source"
    ( cd "$HERE/src/vpn4" && CGO_ENABLED=0 GOOS=linux GOARCH=$(go env GOARCH) \
        go build -trimpath -ldflags '-s -w' -o "$HERE/vpn4" . ) || die "go build failed"
    src=$HERE/vpn4
else
    die "no vpn4 binary: pass VPN4_BIN=, place ./vpn4 next to this script, or install Go"
fi
if [ -f "$BIN" ] && cmp -s "$src" "$BIN"; then
    say "binary unchanged: $BIN"
else
    install -m 0755 "$src" "$BIN"
    changed_bin=1
    say "installed $BIN ($(wc -c <"$src") bytes)"
fi

# ------------------------------------------------------------ 2. configuration
tmp=$(mktemp) && trap 'rm -f "$tmp"' EXIT
cat > "$tmp" <<EOF
# Generated by deploy/nat64/xio-vpn4-setup.sh - read by vpn4.service and vpn4-rules.sh.
# Do not edit by hand: re-run the setup script instead.
PREFIX=$PREFIX
AWG_IF=$AWG_IF
TUN_V4=$TUN_V4
TUN_CIDR=$TUN_CIDR
CLIENT_V4=$CLIENT_V4
TCP_PORT=$TCP_PORT
DNS_PORT=$DNS_PORT
DNS_UPSTREAM=$DNS_UPSTREAM
VPN4_PREFIX=$PREFIX
VPN4_TCP_LISTEN=0.0.0.0:$TCP_PORT
VPN4_DNS_LISTEN=0.0.0.0:$DNS_PORT
VPN4_DNS_UPSTREAM=$DNS_UPSTREAM
EOF
changed_conf=0
if [ -f "$CONF" ] && cmp -s "$tmp" "$CONF"; then
    say "config unchanged: $CONF"
else
    install -m 0644 "$tmp" "$CONF"
    changed_conf=1
    say "wrote $CONF"
fi

# rules script: byte-identical copy of the one shipped next to this script
changed_rules=0
if [ -f "$RULES" ] && cmp -s "$HERE/vpn4-rules.sh" "$RULES"; then
    say "rules script unchanged: $RULES"
else
    install -m 0755 "$HERE/vpn4-rules.sh" "$RULES"
    changed_rules=1
    say "installed $RULES"
fi

# units
changed_units=0
for u in vpn4.service vpn4-rules.service; do
    [ -f "$HERE/$u" ] || die "unit template $u is missing next to this script"
    if [ -f "/etc/systemd/system/$u" ] && cmp -s "$HERE/$u" "/etc/systemd/system/$u"; then
        :
    else
        install -m 0644 "$HERE/$u" "/etc/systemd/system/$u"
        changed_units=1
        say "installed unit $u"
    fi
done
if [ "$changed_units" = 1 ]; then
    systemctl daemon-reload
fi

# ------------------------------------------- 3. AmneziaWG: give the client IPv4
awg_changed=0
if [ -d "$AWG_DIR" ]; then
    setconf=$AWG_DIR/awg0.setconf.conf
    if [ -f "$setconf" ]; then
        v6=$(sed -n 's/^AllowedIPs *= *//p' "$setconf" | tr ',' '\n' | grep ':' | head -1 | tr -d ' ')
        peer_pub=$(awk '/^\[Peer\]/{f=1;next} f&&/^PublicKey/{print $3; exit}' "$setconf")
        if grep -q "^AllowedIPs *= *.*$CLIENT_V4/32" "$setconf"; then
            say "peer already carries $CLIENT_V4/32"
        elif [ -n "$v6" ]; then
            cp -a "$setconf" "$setconf.bak-xio-vpn4"
            sed -i "s|^AllowedIPs = .*|AllowedIPs = $CLIENT_V4/32, $v6|" "$setconf"
            # keep awg0.conf (the human-facing copy) in step with the applied one
            if [ -f "$AWG_DIR/awg0.conf" ] && grep -q '^AllowedIPs' "$AWG_DIR/awg0.conf"; then
                cp -a "$AWG_DIR/awg0.conf" "$AWG_DIR/awg0.conf.bak-xio-vpn4"
                sed -i "s|^AllowedIPs = .*|AllowedIPs = $CLIENT_V4/32, $v6|" "$AWG_DIR/awg0.conf"
            fi
            awg_changed=1
            say "peer AllowedIPs += $CLIENT_V4/32 (v6 part kept: $v6)"
        else
            say "WARNING: no IPv6 AllowedIPs found in $setconf - add $CLIENT_V4/32 by hand"
        fi

        # a ready-to-import client profile: address inside the tunnel + our resolver
        client=$AWG_DIR/client-ipv4.conf
        if [ -f "$client" ] && ! grep -q '^Address' "$client"; then
            cp -a "$client" "$client.bak-xio-vpn4"
            python3 - "$client" "$CLIENT_V4" "$TUN_CIDR" "$v6" "$TUN_V4" <<'PY'
import sys
path, v4, cidr, v6, tun = sys.argv[1:6]
lines = open(path).read().splitlines()
addr = 'Address = %s/%s' % (v4, cidr) + (', ' + v6 if v6 else '')
out, done = [], False
for ln in lines:
    out.append(ln)
    if not done and ln.strip() == '[Interface]':
        out.append(addr)
        out.append('DNS = %s' % tun)
        done = True
open(path, 'w').write('\n'.join(out) + '\n')
PY
            chmod 600 "$client"
            say "client profile $client now carries Address and DNS"
        fi
    fi
else
    say "WARNING: $AWG_DIR is absent - skipping the AmneziaWG part"
fi

# --------------------------------------------------------------- 4. enable/start
systemctl enable vpn4-rules.service vpn4.service >/dev/null 2>&1 || true

if [ "$changed_rules" = 1 ] || [ "$changed_conf" = 1 ] || [ "$awg_changed" = 1 ] \
   || ! systemctl is-active --quiet vpn4-rules.service; then
    systemctl restart vpn4-rules.service
    say "restarted vpn4-rules.service"
fi
if [ "$changed_bin" = 1 ] || [ "$changed_conf" = 1 ] || ! systemctl is-active --quiet vpn4.service; then
    systemctl restart vpn4.service
    say "restarted vpn4.service"
fi
if [ "$awg_changed" = 1 ]; then
    if [ -x "$AWG" ] && ip link show "$AWG_IF" >/dev/null 2>&1; then
        # "awg set peer" only touches that peer, so the live session is not reset
        "$AWG" set "$AWG_IF" peer "$peer_pub" allowed-ips "$CLIENT_V4/32, $v6" \
            || "$AWG" setconf "$AWG_IF" "$AWG_DIR/awg0.setconf.conf" \
            || die "could not apply the new AllowedIPs to $AWG_IF"
        say "applied $CLIENT_V4/32 to peer $peer_pub on $AWG_IF"
    fi
fi

# ------------------------------------------------------------------ 5. summary
sleep 1
printf '\n=== state ===\n'
systemctl is-enabled vpn4 vpn4-rules 2>&1 | sed 's/^/  enabled: /'
systemctl is-active vpn4 vpn4-rules 2>&1 | sed 's/^/  active:  /'
ip -4 addr show dev "$AWG_IF" 2>/dev/null | grep -E 'inet ' | sed 's/^/  /' || echo "  no IPv4 on $AWG_IF"
ss -tlnp 2>/dev/null | grep ":$TCP_PORT " | sed 's/^/  /' || echo "  tcp/$TCP_PORT is not listening"
ss -ulnp 2>/dev/null | grep ":$DNS_PORT " | sed 's/^/  /' || echo "  udp/$DNS_PORT is not listening"
iptables -t nat -S PREROUTING | grep "$TAG" | sed 's/^/  /'
printf '\nnext: journalctl -u vpn4 -f   (every relayed flow logs "-> [<prefix>:<hex>:<hex>]:<port>")\n'
